#!/usr/bin/env bash
# Re-derive every number in the documentation from the data files.
#
# Nothing in docs/ is typed by hand: this script regenerates it, so a price
# change or a new run changes the documents too.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
export PYTHONPATH="$REPO_ROOT/src"

METRICS="${METRICS:-$REPO_ROOT/data/reference_runs/course_h100_20kids_2026-11-14.json}"
OUTPUT="${OUTPUT:-$REPO_ROOT/docs/homework-answers.generated.md}"

echo "==> analysing $METRICS"
python3 -m mediagen analyze --metrics "$METRICS" "$@"

echo
echo "==> writing $OUTPUT"
{
  echo "<!-- Generated by scripts/analyze.sh. Do not edit by hand. -->"
  echo
  python3 -m mediagen report --metrics "$METRICS" "$@"
} > "$OUTPUT"

echo "==> done"
